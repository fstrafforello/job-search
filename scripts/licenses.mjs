// Writes public/third-party-licenses.txt: this app's licence plus the licence of everything shipped inside the exe
// (the Node.js runtime, every production npm package, and the pdf.js parts bundled by unpdf).
// Usage: npm run licenses   (also run by build:exe, so the exe always carries an up-to-date copy)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public', 'third-party-licenses.txt');
const RULE = '='.repeat(78);

const read = (f) => fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n').trim();

function licenceFile(dir) {
  const name = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)([-.][\w.-]+)?$/i.test(f));
  return name ? path.join(dir, name) : null;
}

// Node's lookup: the package's own node_modules, then each parent's.
function resolvePackage(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (dir === ROOT || path.dirname(dir) === dir) return null;
  }
}

// Every package reachable from package.json's "dependencies" (not devDependencies),
// i.e. everything esbuild can bundle into the exe.
function productionPackages() {
  const found = new Map();
  (function walk(dir) {
    const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    for (const name of Object.keys({ ...meta.dependencies, ...meta.optionalDependencies })) {
      const depDir = resolvePackage(name, dir);
      if (!depDir) {
        if (!(name in (meta.optionalDependencies || {}))) throw new Error(`${name} (needed by ${meta.name}) is not installed. Run npm install.`);
        continue;
      }
      if (found.has(depDir)) continue;
      const dep = JSON.parse(fs.readFileSync(path.join(depDir, 'package.json'), 'utf8'));
      found.set(depDir, { name: dep.name, version: dep.version, license: dep.license || dep.licenses?.map((l) => l.type).join(' OR '), path: depDir });
      walk(depDir);
    }
  })(ROOT);
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

async function nodeLicence() {
  const local = licenceFile(path.dirname(process.execPath));
  if (local) return read(local);
  const url = `https://raw.githubusercontent.com/nodejs/node/${process.version}/LICENSE`;
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(20000) });
    if (res.ok) return (await res.text()).replace(/\r\n/g, '\n').trim();
  } catch { /* fall through */ }
  console.warn(`Could not read the Node.js licence; linking to it instead (${url})`);
  return `See ${url}`;
}

const sections = [];
const add = (title, body) => sections.push(`${RULE}\n${title}\n${RULE}\n\n${body}\n`);

add('Job Search Dashboard', `${read(path.join(ROOT, 'NOTICE')).split('\n\n')[0]}\n\n${fs.readFileSync(path.join(ROOT, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n').replace(/^\n+|\s+$/g, '')}`);

add(`Node.js ${process.version} (the runtime inside the exe)`, await nodeLicence());

// Some packages only put their licence in a "License" section of the README.
function readmeLicence(dir) {
  const readme = fs.readdirSync(dir).find((f) => /^readme(\.\w+)?$/i.test(f));
  if (!readme) return null;
  const m = read(path.join(dir, readme)).match(/^#+\s*licen[cs]e\s*\n([\s\S]*?)(?=\n#+\s|(?![\s\S]))/im);
  return m && m[1].trim() ? m[1].trim().replaceAll('&lt;', '<').replaceAll('&gt;', '>') : null;
}

const missing = [];
for (const dep of productionPackages()) {
  const file = licenceFile(dep.path);
  const text = file ? read(file) : readmeLicence(dep.path);
  if (!text) missing.push(dep.name);
  const declared = dep.license ? (dep.license.startsWith('(') ? dep.license : `(${dep.license})`) : '(see package)';
  add(`${dep.name} ${dep.version} ${declared}`,
    text || `No licence text is included in the package. Declared licence: ${dep.license || 'unknown'}.`);
  // unpdf bundles pdf.js and its image decoders; their licences ship in dist/licenses.
  const extra = path.join(dep.path, 'dist', 'licenses');
  if (fs.existsSync(extra)) {
    for (const f of fs.readdirSync(extra).sort()) add(`${dep.name}: bundled ${f.replace(/^LICENSE_/, '')}`, read(path.join(extra, f)));
  }
}

const header = `Licences for Job Search Dashboard and the third-party software it includes.\n` +
  `Generated by scripts/licenses.mjs. Do not edit by hand.\n\n`;
fs.writeFileSync(OUT, header + sections.join('\n'));
console.log(`Wrote ${path.relative(ROOT, OUT)} (${sections.length} sections)` +
  (missing.length ? `; no licence file in: ${missing.join(', ')}` : ''));
